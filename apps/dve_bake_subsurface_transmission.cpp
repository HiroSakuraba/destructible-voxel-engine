// Bakes the subsurface slab-transmission table from the random-walk ground truth
// (subsurface_random_walk.hpp) into
//   src/render/subsurface_transmission_table.inc        (CPU reference)
//   shaders/common/subsurface_transmission_table.hlsli  (GPU)
//
// Entry [mu][A][k]: the share of collimated light arriving at cos(incidence) mu on one face of
// an infinite slab, thickness t = 16 (k/16)^2 Burley scatter distances, that leaves the other
// face after scattering at least once. The medium is Chiang et al.'s for albedo A; isotropic,
// index-matched. Light that crosses without scattering is not counted (it is a straight beam).
//
// Usage: dve_bake_subsurface_transmission <repository root> [walks per entry, default 200000]
#include "dve/render/subsurface_random_walk.hpp"

#include <array>
#include <cmath>
#include <cstdio>
#include <filesystem>
#include <fstream>
#include <limits>
#include <random>
#include <string>
#include <thread>
#include <vector>

#include "dve/render/subsurface_transmission.hpp"

using namespace dve;
using namespace dve::render;

int main(int argc, char** argv) {
    if (argc < 2) {
        std::fprintf(stderr, "usage: %s <repository root> [walks per entry]\n", argv[0]);
        return 2;
    }
    const std::filesystem::path root = argv[1];
    const std::uint64_t walks = argc > 2 ? std::stoull(argv[2]) : 200000ULL;
    constexpr std::size_t kMu = kSubsurfaceTransmissionCosines, kA = kSubsurfaceTransmissionAlbedos,
                          kX = kSubsurfaceTransmissionThicknesses;
    std::vector<float> table(kMu * kA * kX, 0.0F);
    std::vector<std::thread> workers;
    const unsigned threads = std::max(1U, std::min(16U, std::thread::hardware_concurrency()));
    for (unsigned w = 0; w < threads; ++w)
        workers.emplace_back([&, w] {
            for (std::size_t entry = w; entry < table.size(); entry += threads) {
                const std::size_t mi = entry / (kA * kX), ai = (entry / kX) % kA, xi = entry % kX;
                const float mu = subsurface_transmission_cosine(mi), albedo = subsurface_transmission_albedo(ai);
                const float thickness = subsurface_transmission_thickness(xi);
                if (albedo <= 0.0F || thickness <= 0.0F) continue;
                const SubsurfaceMedium medium = subsurface_medium_from_albedo(albedo, 1.0F, 1.0F);   // d = 1 unit
                const SlabSubsurfaceDomain slab(-thickness, 0.0F);
                std::mt19937_64 rng(0x5EEDULL * (entry + 1U));
                std::uniform_real_distribution<double> uniform(0.0, 1.0);
                auto random = [&] { return uniform(rng); };
                const Float3 incoming{std::sqrt(1.0F - mu * mu), -mu, 0.0F};
                std::uint64_t through = 0;
                for (std::uint64_t i = 0; i < walks; ++i) {
                    const auto walk = enter_and_walk_subsurface(slab, medium, {0, 0, 0}, {0, 1, 0}, incoming, random);
                    if (walk && walk->end == RandomWalkResult::End::Exited && walk->normal.y < 0.0F && walk->events > 0U)
                        ++through;
                }
                table[entry] = static_cast<float>(static_cast<double>(through) / static_cast<double>(walks));
            }
        });
    for (std::thread& t : workers) t.join();

    const auto write = [&](const std::filesystem::path& path, const std::string& head, const std::string& open,
                           const std::string& close) {
        std::ofstream out(path, std::ios::trunc);
        out << head << open;
        for (std::size_t i = 0; i < table.size(); ++i) {
            if (i % kX == 0) out << "\n   ";
            char value[32];
            std::snprintf(value, sizeof(value), " %.5fF,", static_cast<double>(table[i]));
            out << value;
        }
        out << "\n" << close;
    };
    const std::string about =
        "// Generated by apps/dve_bake_subsurface_transmission.cpp from the subsurface random walk (" +
        std::to_string(walks) +
        " walks per entry). Do not edit.\n"
        "// [cosine of incidence][albedo][thickness]: see dve/render/subsurface_transmission.hpp.\n";
    write(root / "src/render/subsurface_transmission_table.inc", about, "{", "}\n");
    write(root / "shaders/common/subsurface_transmission_table.hlsli",
          about + "#ifndef DVE_SUBSURFACE_TRANSMISSION_TABLE_HLSLI\n#define DVE_SUBSURFACE_TRANSMISSION_TABLE_HLSLI\n\n",
          "static const float kSubsurfaceTransmissionTable[" + std::to_string(table.size()) + "] = {",
          "};\n\n#endif // DVE_SUBSURFACE_TRANSMISSION_TABLE_HLSLI\n");
    std::printf("baked %zu entries, %llu walks each\n", table.size(), static_cast<unsigned long long>(walks));
    return 0;
}
